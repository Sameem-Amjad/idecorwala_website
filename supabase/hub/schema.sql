-- ============================================================================
-- iDecorwala marketing site (app tag `idecorwala`) — shared Supabase hub schema
-- ============================================================================
-- Self-contained and re-runnable: drops and rebuilds everything inside the
-- `idecorwala` schema. Run as `postgres` in ONE transaction, e.g.
--
--   psql "$HUB_DB_URL" -v ON_ERROR_STOP=1 --single-transaction -f supabase/hub/schema.sql
--
-- After the first run, add `idecorwala` to Dashboard → Project Settings → API
-- → "Exposed schemas" so PostgREST (supabase-js) can reach it.
--
-- Inferred from src/lib/supabaseClient.ts (the only data access in the app):
--   product_categories  — navbar / footer / /products / /products/[slug]
--   products            — joined to categories (FK powers `product_categories(*)`)
--   blogs               — /company/thought-leadership (+ /[slug]) and home page
--
-- The site is read-only for visitors: anon/authenticated may SELECT active /
-- published rows only. Content is managed by the owner in the Supabase
-- dashboard (postgres role) or by the service_role key. No Supabase Auth is
-- used (no auth.users trigger) and no Storage bucket is referenced (images are
-- plain URLs / /public paths).
-- ============================================================================

drop schema if exists idecorwala cascade;
create schema idecorwala;

-- ----------------------------------------------------------------------------
-- updated_at helper
-- ----------------------------------------------------------------------------
create function idecorwala.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

-- ----------------------------------------------------------------------------
-- product_categories
-- ----------------------------------------------------------------------------
create table idecorwala.product_categories (
  id              bigint generated by default as identity primary key,
  name            text not null,
  slug            text not null unique,
  description     text,
  category_order  integer not null default 0,
  hero_title      text,
  hero_subtitle   text,
  hero_image_url  text,
  is_active       boolean not null default true,
  created_at      timestamptz not null default now()
);
create index product_categories_active_order_idx
  on idecorwala.product_categories (category_order) where is_active;

-- ----------------------------------------------------------------------------
-- products
-- ----------------------------------------------------------------------------
create table idecorwala.products (
  id             bigint generated by default as identity primary key,
  category_id    bigint not null
                 references idecorwala.product_categories (id) on delete cascade,
  name           text not null,
  description    text,
  image_url      text,
  redirect_url   text not null default '',
  display_order  integer not null default 0,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now(),
  constraint products_category_name_key unique (category_id, name)
);
create index products_category_idx on idecorwala.products (category_id);
create index products_active_order_idx
  on idecorwala.products (display_order) where is_active;

-- ----------------------------------------------------------------------------
-- blogs (thought leadership)
-- ----------------------------------------------------------------------------
create table idecorwala.blogs (
  id              bigint generated by default as identity primary key,
  title           text not null,
  slug            text not null unique,
  excerpt         text not null default '',
  cover_image     text not null default '',
  category        text not null default '',
  tags            text[] not null default '{}',
  author          text not null default 'iDecorwala Editorial',
  published_date  date not null default current_date,
  reading_time    text not null default '5',   -- minutes; UI strips non-digits
  content         jsonb,                        -- { "blocks": BlogBlock[] }
  is_published    boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index blogs_published_date_idx
  on idecorwala.blogs (published_date desc) where is_published;
create index blogs_tags_idx on idecorwala.blogs using gin (tags);

create trigger blogs_set_updated_at
  before update on idecorwala.blogs
  for each row execute function idecorwala.set_updated_at();

-- ============================================================================
-- Grants (hub convention)
-- ============================================================================
grant usage on schema idecorwala to anon, authenticated, service_role;

grant all on all tables    in schema idecorwala to anon, authenticated, service_role;
grant all on all routines  in schema idecorwala to anon, authenticated, service_role;
grant all on all sequences in schema idecorwala to anon, authenticated, service_role;

alter default privileges for role postgres in schema idecorwala
  grant all on tables    to anon, authenticated, service_role;
alter default privileges for role postgres in schema idecorwala
  grant all on routines  to anon, authenticated, service_role;
alter default privileges for role postgres in schema idecorwala
  grant all on sequences to anon, authenticated, service_role;

-- ============================================================================
-- Row Level Security — public catalog read, service_role writes
-- ============================================================================
alter table idecorwala.product_categories enable row level security;
alter table idecorwala.products           enable row level security;
alter table idecorwala.blogs              enable row level security;

create policy idecorwala_product_categories_public_read
  on idecorwala.product_categories
  for select to anon, authenticated
  using (is_active);

create policy idecorwala_products_public_read
  on idecorwala.products
  for select to anon, authenticated
  using (is_active);

create policy idecorwala_blogs_public_read
  on idecorwala.blogs
  for select to anon, authenticated
  using (is_published);

-- service_role bypasses RLS anyway; explicit for clarity. No anon/authenticated
-- write policies => visitors cannot insert/update/delete.
create policy idecorwala_product_categories_service_all
  on idecorwala.product_categories for all to service_role using (true) with check (true);
create policy idecorwala_products_service_all
  on idecorwala.products for all to service_role using (true) with check (true);
create policy idecorwala_blogs_service_all
  on idecorwala.blogs for all to service_role using (true) with check (true);
